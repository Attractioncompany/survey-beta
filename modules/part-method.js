  return `<div class="pm-pipe">${P.steps.map(([k, v], i) =>
    `<div class="pm-step"><b>${String(i + 1).padStart(2, "0")}</b>
       <div><strong>${k}</strong><p>${v}</p></div></div>`).join("")}

    <p class="pm-caution">${P.caution}</p></div>`;
