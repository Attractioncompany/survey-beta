/** 판단 기준 표. now = 지금 내 칸의 key(없으면 어느 칸도 강조하지 않는다).
 *  지금 여기는 텍스트 배지가 아니라 **가로 게이지**로 먼저 보여준다(대표 R 2026-08-29
 *  "내가 어디에 있는지는 명확하게 가시적으로 드러나야 함"). 칸 나눔은 분포 기반 밴드
 *  그대로다 — 수치 기준선을 새로 긋지 않는다(이론 게이트). */
export function bandBlock(id, now){
  const rows = BANDS[id === "nosemouth" ? "mouth" : id];
  if(!rows || !rows.length) return "";
  const cur = rows.findIndex(r=>r.key === now);
  const scale = cur >= 0 ? `<div class="pm-scale">${rows.map((r,i)=>
    `<div class="pm-seg${i === cur ? " on" : ""}"><i></i><span>${r.name}</span></div>`).join("")}</div>
    <p class="pm-now">지금 여기 — ${rows[cur].name}</p>` : "";
  return `<div class="pm-bands"><b>이런 기준으로 봤습니다</b>${scale}${rows.map(r=>
    `<div class="pm-band${r.key === now ? " on" : ""}">
       <span class="pm-tag">${r.name}${r.key === now ? " · 지금 여기" : ""}</span>
       <p>${r.desc}</p>
     </div>`).join("")}</div>`;
}
